// One-off generator for src/core/words-en.js.
// Usage: node scripts/make-wordlist.js cefrj-vocabulary-profile-1.5.csv octanove-vocabulary-profile-c1c2-1.0.csv
// Sources: CEFR-J Vocabulary Profile 1.5 (Tono Laboratory, TUFS; free with attribution) and Octanove C1/C2 (CC BY-SA 4.0),
// both from https://github.com/openlanguageprofiles/olp-en-cefrj
const fs = require('node:fs');
const path = require('node:path');

const LEVELS = ['A1', 'A2', 'B1', 'B2', 'C1', 'C2'];
const best = new Map(); // word -> lowest level index

for (const file of process.argv.slice(2)) {
  const [, ...rows] = fs.readFileSync(file, 'utf8').split(/\r?\n/);
  for (const row of rows) {
    const [headword, , level] = row.split(',');
    const rank = LEVELS.indexOf(level);
    if (!headword || rank < 0) continue;
    for (const w of headword.split('/')) {
      const word = w.trim().toLowerCase();
      // Single plain words only: phrases ("a lot of") and abbreviations ("a.m.") are never quizzed.
      if (!/^[a-z]+(?:'[a-z]+)?$/.test(word) || word.length < 2) continue;
      if (!best.has(word) || best.get(word) > rank) best.set(word, rank);
    }
  }
}

const out = {};
for (const [word, rank] of [...best].sort((a, b) => a[0].localeCompare(b[0]))) (out[LEVELS[rank]] ||= []).push(word);

const body = LEVELS.map(l => `    ${l}: ${JSON.stringify((out[l] || []).join(' '))},`).join('\n');
fs.writeFileSync(path.join(__dirname, '../src/core/words-en.js'), `// GENERATED by scripts/make-wordlist.js. Do not edit.
// CEFR-J Vocabulary Profile 1.5 (c) Tono Laboratory, TUFS, used with attribution; C1/C2 from the Octanove Vocabulary Profile (CC BY-SA 4.0).
(() => {
  const DS = (globalThis.DS ||= {});
  DS.WORDS_EN = {
${body}
  };
  if (typeof module === 'object') module.exports = DS;
})();
`);
console.log(Object.fromEntries(LEVELS.map(l => [l, (out[l] || []).length])));
