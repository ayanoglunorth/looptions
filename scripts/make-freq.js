// One-off generator for src/core/freq-en.js.
// Usage: node scripts/make-freq.js en_50k.txt
// Source: hermitdave/FrequencyWords en_50k.txt (OpenSubtitles 2018; content CC-BY-SA-4.0, code MIT).
const fs = require('node:fs');
const path = require('node:path');
require('../src/core/words-en.js');
const DS = require('../src/core/vocab.js');

const MAX = 9000;
const listed = new Set(Object.values(DS.WORDS_EN).flatMap(l => l.split(' ')));
const total = new Map(); // headword -> summed count of its forms
for (const line of fs.readFileSync(process.argv[2], 'utf8').split(/\r?\n/)) {
  const [word, count] = line.split(' ');
  if (!/^[a-z]+$/.test(word || '')) continue;
  // A listed word counts as itself ("thing" must not fold into "the"); anything else folds into its headword.
  const key = listed.has(word) ? word : DS.headword(word)?.word;
  if (key) total.set(key, (total.get(key) || 0) + Number(count));
}
// Only words of the CEFR lists are kept (no names or slang); a word counts once, under its headword.
const words = [...total].sort((a, b) => b[1] - a[1]).map(([w]) => w).filter(w => /^[a-z]{2,}$/.test(w)).slice(0, MAX);

fs.writeFileSync(path.join(__dirname, '../src/core/freq-en.js'), `// GENERATED by scripts/make-freq.js. Do not edit.
// Word order from hermitdave/FrequencyWords (OpenSubtitles 2018, CC-BY-SA-4.0), restricted to CEFR list headwords; most frequent first.
(() => {
  const DS = (globalThis.DS ||= {});
  DS.FREQ_EN = ${JSON.stringify(words.join(' '))};
  if (typeof module === 'object') module.exports = DS;
})();
`);
console.log(words.length, words.slice(0, 10).join(' '));
